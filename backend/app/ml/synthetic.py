"""Synthetic, clearly-labelled training/evaluation data for the anomaly detector.

IMPORTANT: everything produced here is SYNTHETIC. Metrics computed on it show that the
pipeline works and is reproducible; they are *not* evidence of real-world accuracy.
"""
from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from ..simulation.profiles import PROFILES, normal_reading
from .features import FEATURE_NAMES, ReadingContext, extract

ANOMALY_KINDS = ("overconsumption", "spike", "voltage_fault", "low_power_factor", "phantom_load")
DATA_LABEL = "synthetic (generated by app.ml.synthetic — not real measurements)"


def anomalous_reading(
    rng: np.random.Generator, kind: str, rated_w: float, prev_power: float | None
) -> tuple[float, float, float, bool]:
    """Return (power_w, voltage_v, current_a, relay_on) exhibiting the given anomaly kind."""
    v = float(rng.normal(230, 2.5))
    pf = float(rng.uniform(0.85, 0.97))
    relay = True
    if kind == "overconsumption":
        p = rated_w * float(rng.uniform(1.6, 3.0))
    elif kind == "spike":
        p = rated_w * float(rng.uniform(2.5, 5.0))
    elif kind == "voltage_fault":
        v = float(rng.choice([rng.uniform(165, 195), rng.uniform(255, 275)]))
        p = rated_w * float(rng.uniform(0.8, 1.0))
    elif kind == "low_power_factor":
        p = rated_w * float(rng.uniform(0.8, 1.0))
        pf = float(rng.uniform(0.25, 0.5))
    elif kind == "phantom_load":
        relay = False
        p = rated_w * float(rng.uniform(0.2, 0.6))
    else:  # pragma: no cover - guarded by callers
        raise ValueError(kind)
    return p, v, p / (v * pf), relay


@dataclass
class Dataset:
    X: np.ndarray
    y: np.ndarray  # 1 = anomaly, 0 = normal
    kinds: np.ndarray  # anomaly kind or "normal"
    feature_names: list[str]
    label: str = DATA_LABEL


def generate(n_appliances: int = 40, steps: int = 400, anomaly_rate: float = 0.03, seed: int = 42) -> Dataset:
    """Generate per-appliance sequences of readings with injected, labelled anomalies."""
    rng = np.random.default_rng(seed)
    types = [t for t in PROFILES if t != "other"]
    X, y, kinds = [], [], []
    for _ in range(n_appliances):
        a_type = types[int(rng.integers(len(types)))]
        prof = PROFILES[a_type]
        rated = prof.rated_w * float(rng.uniform(0.8, 1.25))
        standby = max(5.0, rated * 0.03)
        on = bool(rng.random() < 0.6)
        prev_power: float | None = None
        prev_ratio: float | None = None
        for _ in range(steps):
            if rng.random() < 0.03:  # occasional switching
                on = not on
            if rng.random() < anomaly_rate:
                kind = ANOMALY_KINDS[int(rng.integers(len(ANOMALY_KINDS)))]
                p, v, i, relay = anomalous_reading(rng, kind, rated, prev_power)
                label = 1
            else:
                kind = "normal"
                p, v, i = normal_reading(rng, a_type, rated, on, prev_ratio)
                relay = on
                label = 0
                # AC / fridge compressor cycling: a normal on-state can briefly drop to fan-only
                if on and prof.cycling and rng.random() < 0.15:
                    p *= 0.25
                    i *= 0.25
            X.append(extract(ReadingContext(p, rated, standby, v, i, relay, prev_power)))
            y.append(label)
            kinds.append(kind)
            prev_power = p
            prev_ratio = p / rated if on else None
    return Dataset(np.vstack(X), np.array(y, dtype=int), np.array(kinds), list(FEATURE_NAMES))
